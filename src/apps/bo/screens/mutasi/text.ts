export type MutKey = keyof typeof MUT_TEXT;

export function mut(key: MutKey, values: Readonly<Record<string, string>> = {}): string {
  return Object.entries(values).reduce<string>(
    (text, [name, value]) => text.replaceAll(`{${name}}`, value),
    MUT_TEXT[key],
  );
}
