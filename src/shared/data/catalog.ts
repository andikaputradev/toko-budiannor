export interface FamilySpec {
  readonly name: string;
  readonly category: string;
  readonly baseUnit: string;
  readonly decimal: boolean;
  readonly units: readonly (readonly [string, number])[];
  readonly variants: readonly string[];
  readonly priceMin: number;
  readonly priceMax: number;
  readonly stockScale: number;
}

const PVC =
  '1/2 inci|3/4 inci|1 inci|1,25 inci|1,5 inci|2 inci|2,5 inci|3 inci|4 inci|5 inci|6 inci|8 inci';
const COLORS =
  'Putih|Gading|Krem|Abu Muda|Abu Tua|Biru Muda|Hijau Muda|Kuning|Oranye|Merah Bata|Coklat|Hitam';

function family(
  name: string,
  category: string,
  baseUnit: string,
  decimal: boolean,
  units: readonly (readonly [string, number])[],
  variants: string,
  priceMin: number,
  priceMax: number,
  stockScale: number,
): FamilySpec {
  return {
    name,
    category,
    baseUnit,
    decimal,
    units,
    variants: variants.split('|'),
    priceMin,
    priceMax,
    stockScale,
  };
}

