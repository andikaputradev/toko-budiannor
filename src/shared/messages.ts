export type SystemMessageId = keyof typeof systemMessages;
export type LabelKey = keyof typeof labels;
export type MessageValues = Readonly<Record<string, string | number>>;

function fillLabel(template: string, values: MessageValues): string {
  return template.replace(/\{(\w+)\}/g, (placeholder: string, name: string) => {
    const value = values[name];
    return value === undefined ? placeholder : String(value);
  });
}

export function message(id: SystemMessageId, values: MessageValues = {}): string {
  let text: string = systemMessages[id];
  for (const parameter of messageParameters[id] ?? []) {
    const value = values[parameter.name];
    if (value !== undefined) {
      text = text.replace(parameter.example, String(value));
    }
  }
  return text;
}

export function label(key: LabelKey, values: MessageValues = {}): string {
  return fillLabel(labels[key], values);
}
